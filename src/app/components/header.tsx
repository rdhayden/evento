'use client';

import Link from 'next/link';
import Logo from './logo';
import { usePathname } from 'next/navigation';
import { motion } from 'framer-motion';
import { cn } from '@/lib/utils';

const routes = [
  { name: 'Home', path: '/' },
  { name: 'All Events', path: '/events/all' },
];

/*
Tailwind styles used below:

flex items-center justify-between -- sequences items, centring them vertically and spacing them out horizontally
border-b border-white/10 h-14 px-3 sm:px-9 -- bottom border with 10% opacity white, height 14, horizontal padding 3
                                              on the smallest mobile screens and 9 on small (sm) screens and up
flex gap-x-6 text-sm -- flex container with horizontal gap 6 and small text
text-white/50 hover:text-white transition -- 50% opacity white text, changing to full white on hover
                                            with a transition (default 150ms ease-in-out)
*/

// note using a hook usePathname to get the current pathname, generally when using hooks
// in a component in Next.js, the component must be a client component
// in this case we're getting the path from the client side navigation
// so we need to set 'use client' at the top of the file
export default function Header() {
  const activePathname = usePathname(); // next hook to get the current pathname (e.g. /events/all)

  return (
    /* sequences items, center them vertically, spacing them out horizontally, bottom border, border white 10% opacity
    height 14, horizontal padding 3 on the smallest mobile screens and 9 on small (sm) screens and up*/
    <header className="flex items-center justify-between border-b border-white/10 h-14 px-3 sm:px-9">
      <Logo />
      <nav className="h-full">
        <ul className="flex gap-x-6 h-full text-sm">
          {/*flex container with horizontal gap 6 and small text */}
          {/* transition defaults to 150ms ease-in-out. relative position of the li added to enable absolute
          positioning of the active link indicator relative to the li. absolute removes the div from the document flow.

          cn combines clsx and twMerge
            clsx is a utility for constructing className strings conditionally
            twMerge ensures that if there is a conflict in Tailwind classes
            the latter class takes precedence
          */}
          {routes.map((route) => (
            <li
              key={route.path}
              className={cn(
                'hover:text-white flex items-center relative transition',
                {
                  'text-white': activePathname === route.path,
                  'text-white/50': activePathname !== route.path,
                }
              )}
            >
              <Link href={route.path}>{route.name}</Link>
              {/*framer motion div used to manage the animation of a line underlining the active link
              this is like anormal div, given height 1 and full width of the container, absolutely positioned
              at bottom 0 of the li and coloured with the accent colour.
              The layoutID lets framer motion link the divs from both motion.divs generated by the map
              which is how it manages the animation to transition smoothly between them*/}
              {activePathname === route.path && (
                <motion.div
                  layoutId="header-active-link"
                  className="bg-accent h-1 w-full absolute bottom-0"
                ></motion.div>
              )}
            </li>
          ))}
        </ul>
      </nav>
    </header>
  );
}
